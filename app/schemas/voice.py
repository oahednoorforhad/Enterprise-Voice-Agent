"""Voice interaction schemas for Sprint 4.

Defines the WebSocket message protocol between the browser and the FastAPI
voice proxy, plus the call summary structure generated after each session.

AudioWorklet Contract
---------------------
- Input  (browser → backend): PCM 24 kHz, 16-bit, mono, base64-encoded.
  The AudioWorkletProcessor in ``frontend/public/audio-worklet-processor.js``
  resamples from the device's native rate (typically 48 kHz or 44.1 kHz) to
  24 kHz using linear interpolation, then packs the signal as Int16Array bytes
  before base64-encoding.
- Output (backend → browser): same format — 24 kHz, 16-bit, mono PCM,
  base64-encoded. The browser decodes and schedules playback via AudioContext.
- Gemini Live expects ``audio/pcm;rate=24000`` on both send and receive.
"""

from __future__ import annotations

from enum import Enum

from pydantic import BaseModel


class VoiceEventType(str, Enum):
    """Discriminator for messages exchanged over the voice WebSocket."""

    # Sent by browser
    AUDIO_CHUNK = "audio_chunk"
    END_OF_AUDIO = "end_of_audio"
    INTERRUPT = "interrupt"
    PLAYBACK_COMPLETE = "playback_complete"  # browser finished playing Gemini's audio

    # Sent by server
    SESSION_STARTED = "session_started"
    SESSION_ENDED = "session_ended"
    TRANSCRIPT = "transcript"
    TOOL_CALL = "tool_call"
    ERROR = "error"
    GENERATION_COMPLETE = "generation_complete"  # Gemini finished generating audio
    INTERRUPTED = "interrupted"                  # Gemini interrupted mid-speech; browser must cancel queued audio


class VoiceEvent(BaseModel):
    """Single WebSocket message in either direction.

    Not all fields are populated for every event type — only the fields
    relevant to the ``type`` are set.

    Browser → Server
    ----------------
    - ``audio_chunk``:  ``data`` = base64 PCM bytes (24 kHz, 16-bit, mono)
    - ``end_of_audio``: no extra fields
    - ``interrupt``:    no extra fields

    Server → Browser
    ----------------
    - ``session_started``: ``session_id``
    - ``audio_chunk``:     ``data`` = base64 PCM bytes
    - ``transcript``:      ``role`` + ``text``
    - ``tool_call``:       ``tool_name`` + ``status`` ("calling" | "done")
    - ``session_ended``:   ``session_id``
    - ``error``:           ``message``
    """

    type: VoiceEventType
    data: str | None = None
    text: str | None = None
    role: str | None = None
    tool_name: str | None = None
    status: str | None = None
    session_id: str | None = None
    message: str | None = None


class CallSummaryResult(BaseModel):
    """Post-session call summary generated by the LLM (FR-10).

    Persisted as JSON to ``ConversationSession.summary`` after a voice
    session ends.  Exposed via ``GET /api/v1/voice/summary/{session_id}``.
    """

    session_id: str
    conversation_summary: str
    sources_used: list[str]
    reasoning_summary: str
    recommended_next_actions: list[str]
